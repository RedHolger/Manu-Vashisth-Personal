"""Synthetic incident corpus for IncidentReplay (P12-01 raw evidence).

Every log file used by this project is generated here from a fixed scenario
table, so the bytes — and therefore the sha256 provenance manifest — are
reproducible run after run. Nothing is copied from a real system: hosts,
actors, object names and every IP address are invented, and all addresses
come from ranges reserved for documentation and benchmarking (RFC 5737
192.0.2.0/24, 198.51.100.0/24, 203.0.113.0/24 and RFC 2544 198.18.0.0/15).

Two raw formats are emitted so the P12-01 adapters have something real to
parse:

* ``audit.jsonl`` — one JSON object per line, written by the application in
  UTC with explicit ``+00:00`` offsets and a per-scenario ``seq`` counter.
* ``edge-syslog.log`` — RFC 3164-style ``key=value`` lines from an edge
  forwarder. Depending on the scenario the forwarder writes in ``+09:00``
  with a clock that runs ``syslog_skew_seconds`` fast (unsynchronized), or in
  UTC with a synchronized clock. Three origins are therefore possible for an
  event: ``audit`` (application only), ``audit+syslog`` (same ``event_id`` in
  both sources — the dedup/clock-skew case) and ``syslog`` (edge device is the
  *sole* source — the cross-source ordering case).

A scenario also declares events that never reach any file
(``omit_from_files``): they are lost to rotation in the fiction, and the
ingestor must report the ``seq`` hole as uncertainty. Those ids are recorded
in ``groundtruth.py`` as *absent* evidence and must never be cited as support
for a finding.

This module carries no labels. Malicious/benign ground truth lives in
``groundtruth.py`` and is consulted only by the evaluation layer.
"""
