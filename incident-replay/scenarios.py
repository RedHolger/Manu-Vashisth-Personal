def logical_events(scenario_id):
    """Assign stable ids and seq numbers to a scenario's logical events."""
    if scenario_id not in _BUILDERS:
        raise KeyError('unknown scenario %r' % (scenario_id,))
    raw, baseline = _BUILDERS[scenario_id]()
    events = []
    for index, event in enumerate(raw, start=1):
        event = dict(event)
        event['id'] = '%s-%06d' % (scenario_id.split('-')[0], index)
        event['seq'] = index
        event['scenario'] = scenario_id
        events.append(event)
    return events, baseline


def _json_record(event):
    return {'event_id': event['id'],
            'ts': event['t'].astimezone(UTC).isoformat(),
            'actor': event['user'],
            'src_ip': event['ip'],
            'event_type': KIND_TO_EVENT_TYPE[event['kind']],
            'action': event['action'],
            'bytes_out': event['bytes_out'],
            'object': event['object'],
            'ticket_ref': event['ticket_ref'],
            'session_id': event['session_id'],
            'session_type': event['session_type'],
            'auth_factors': event['auth_factors'],
            'seq': event['seq']}


def syslog_line(event, host=None, zone=None, skew=None, proc='authd',
                pid=4411):
    """Render one logical event as an RFC 3164-style forwarder line."""
    source = SCENARIO_SOURCES.get(event['scenario'], {})
    zone = source.get('zone', JST) if zone is None else zone
    skew = source.get('syslog_skew_seconds', FORWARDER_SKEW_SECONDS) \
        if skew is None else skew
    local = (event['t'] + dt.timedelta(seconds=skew)).astimezone(zone)
    stamp = '%s %2d %02d:%02d:%02d' % (
        local.strftime('%b'), local.day, local.hour, local.minute,
        local.second)
    fields = ['event_id=%s' % event['id'], 'ts=%s' % local.isoformat(),
              'actor=%s' % event['user'], 'src_ip=%s' % event['ip'],
              'event_type=%s' % KIND_TO_EVENT_TYPE[event['kind']],
              'action=%s' % event['action'],
              'bytes_out=%d' % event['bytes_out'],
              'object=%s' % event['object'],
              'ticket_ref=%s' % event['ticket_ref'],
              'session_id=%s' % event['session_id'],
              'session_type=%s' % event['session_type'],
              'auth_factors=%s' % ('|'.join(event['auth_factors'])),
              'seq=%d' % event['seq']]
    return '%s %s %s[%d]: %s' % (
        stamp, host or event['host'] or source.get('host', 'edge-host'),
        proc, pid, ' '.join(fields))


def scenario_files(scenario_id, root=None):
    """Write one scenario's raw sources; return its file manifest rows."""
    root = Path(root) if root else FIXTURE_ROOT
    events, baseline = logical_events(scenario_id)
    directory = root / scenario_id
    directory.mkdir(parents=True, exist_ok=True)

    written = [event for event in events if not event['omit_from_files']]
    audit_events = [event for event in written
                    if event['origin'] in ('audit', 'audit+syslog')]
    syslog_events = [event for event in written
                     if event['origin'] in ('audit+syslog', 'syslog')]

    rows = []
    audit = directory / 'audit.jsonl'
    audit.write_text(''.join(json.dumps(_json_record(event), sort_keys=True)
                             + '\n' for event in audit_events),
                     encoding='utf-8')
    rows.append(_file_row(audit, 'json-audit', scenario_id,
                          len(audit_events)))
    if syslog_events:
        syslog = directory / 'edge-syslog.log'
        syslog.write_text(''.join(syslog_line(event) + '\n'
                                  for event in syslog_events),
                          encoding='utf-8')
        rows.append(_file_row(syslog, 'syslog-kv', scenario_id,
                              len(syslog_events)))

    baseline_path = directory / 'baseline.json'
    baseline_path.write_text(json.dumps(
        dict(baseline, scenario=scenario_id,
             source='asset-owner configuration (synthetic)',
             note='detector input, not a label'),
        indent=2, sort_keys=True) + '\n', encoding='utf-8')
    rows.append(_file_row(baseline_path, 'baseline-config', scenario_id, 0))
    return rows


def _file_row(path, fmt, scenario_id, records):
    data = path.read_bytes()
    return {'path': str(path.relative_to(path.parent.parent)),
            'absolute_path': str(path), 'scenario': scenario_id,
            'format': fmt, 'records': records, 'bytes': len(data),
            'sha256': hashlib.sha256(data).hexdigest()}


